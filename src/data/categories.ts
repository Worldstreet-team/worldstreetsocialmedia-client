/**
 * WorldStreet content taxonomy — 100 categories across 14 verticals.
 *
 * This is THE shared vocabulary between the client and the ranking algorithm:
 * onboarding interests, post/video tagging, explore browsing, and the feed's
 * candidate pool all key off `ContentCategory.id`.
 *
 * Rules that keep the algorithm honest:
 *
 * - **`id` is a permanent key.** Once shipped, an id is never renamed or
 *   reused — user interest vectors, post tags and engagement counters on the
 *   gateway are stored against it. Retire a category by deleting the entry and
 *   adding a `LEGACY_CATEGORY_ALIASES` mapping, never by re-pointing an id.
 * - **`label` is display-only.** Free to reword, translate, or localize.
 * - **`keywords` feed the classifier** (`classifyText` in `@/lib/categories`).
 *   They are lowercase match hints — hashtags, phrases, tickers, slang — not
 *   an exhaustive dictionary. Cheap to extend; extending them changes tagging
 *   quality, never stored data.
 * - **`videoFirst`** marks categories that skew short-form video. Every
 *   category is valid for both posts and videos; this only hints the video
 *   feed's candidate ordering.
 * - **`sensitive`** marks categories that must be opt-in / down-ranked in the
 *   default ("For You") pool — politics, betting, health advice, faith. They
 *   still rank normally for users who explicitly selected them.
 *
 * Geography is a SEPARATE dimension (`REGIONS`) — a post is `football-soccer`
 * + `africa`, never a "Nigerian football" category. Crossing the two axes is
 * what makes the taxonomy work worldwide without exploding.
 */

export type VerticalId =
	| "markets"
	| "web3"
	| "business"
	| "tech"
	| "news"
	| "sports"
	| "gaming"
	| "entertainment"
	| "music"
	| "lifestyle"
	| "health"
	| "arts"
	| "creator"
	| "learning";

export interface ContentVertical {
	id: VerticalId;
	label: string;
	/** One-line description, used as the group blurb in pickers. */
	blurb: string;
}

export interface ContentCategory {
	/** Permanent algorithm key. Never rename, never reuse. */
	id: string;
	label: string;
	vertical: VerticalId;
	/** Lowercase classifier hints: phrases, hashtags, slang, tickers. */
	keywords: string[];
	/** Skews short-form video — hints the video feed's candidate pool. */
	videoFirst?: boolean;
	/** Opt-in only: excluded from the default pool unless the user picked it. */
	sensitive?: boolean;
}

